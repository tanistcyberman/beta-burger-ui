export const getCategoryTranslation = (catName: string, lang: Language): string => {
  const found = EXPENSE_CATEGORIES.find(
    (c) => c.id === catName || c.en === catName || c.am === catName
  );
  if (found) {
    return lang === 'am' ? found.am : found.en;
  }
  return catName;
};

